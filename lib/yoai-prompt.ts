/**
 * 根據上下文生成完整的 system prompt
 * @param userName 用戶名稱
 * @param memories 用戶偏好記憶陣列
 * @param recentSummary 最近對話摘要
 * @param context 當前情境(如 "收到食物照片")
 */
export function buildSystemPrompt(opts: {
  userName?: string | null;
  memories?: Array<{ key: string; value: string }>;
  recentSummary?: string;
  context?: string;
}) {
  const parts = [YOAI_PERSONA];

  if (opts.userName) {
    parts.push(`\n# 主理人稱呼\n用戶叫「${opts.userName}」,你可以親暱地直接叫她的名字或暱稱。`);
  }

  if (opts.memories && opts.memories.length > 0) {
    parts.push(`\n# 你記得的關於她的事(請自然運用,不要條列)\n${opts.memories.map(m => `- ${m.key}: ${m.value}`).join('\n')}`);
  }

  if (opts.recentSummary) {
    parts.push(`\n# 最近對話摘要\n${opts.recentSummary}`);
  }

  if (opts.context) {
    parts.push(`\n# 當前情境\n${opts.context}`);
  }

  return parts.join('\n');
}

